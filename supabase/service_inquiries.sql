-- ASTRO MOBILE service inquiry workflow
create table if not exists public.service_inquiries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  service_type text not null check (service_type in ('maintenance','software','remote_programming')),
  device_model text not null check (char_length(trim(device_model)) between 2 and 120),
  request_details text not null check (char_length(trim(request_details)) between 3 and 2000),
  status text not null default 'new' check (status in ('new','in_progress','answered','unavailable','awaiting_payment','payment_submitted','paid','closed')),
  admin_reply text,
  quoted_price numeric(10,2) check (quoted_price is null or quoted_price >= 0),
  whatsapp_phone text,
  whatsapp_consent boolean not null default false,
  receipt_path text,
  payment_submitted_at timestamptz,
  payment_confirmed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint remote_contact_consent check (service_type <> 'remote_programming' or ((whatsapp_phone is null and whatsapp_consent=false) or (whatsapp_phone is not null and whatsapp_consent=true))),
  constraint in_person_no_remote_payment check (service_type='remote_programming' or (receipt_path is null and whatsapp_phone is null and whatsapp_consent=false))
);
alter table public.service_inquiries enable row level security;
-- Data API privileges; row access remains restricted by the RLS policies below.
grant select, insert, update on table public.service_inquiries to authenticated;
drop policy if exists "Customers create own service inquiries" on public.service_inquiries;
create policy "Customers create own service inquiries" on public.service_inquiries for insert to authenticated with check (auth.uid()=user_id);
drop policy if exists "Customers read own service inquiries" on public.service_inquiries;
create policy "Customers read own service inquiries" on public.service_inquiries for select to authenticated using (auth.uid()=user_id or (auth.jwt()->>'email')='ahmedkabar.ak@gmail.com');
drop policy if exists "Admin manages service inquiries" on public.service_inquiries;
create policy "Admin manages service inquiries" on public.service_inquiries for all to authenticated using ((auth.jwt()->>'email')='ahmedkabar.ak@gmail.com') with check ((auth.jwt()->>'email')='ahmedkabar.ak@gmail.com');
drop policy if exists "Customers submit remote service payment" on public.service_inquiries;
create policy "Customers submit remote service payment" on public.service_inquiries for update to authenticated
using (auth.uid()=user_id and service_type='remote_programming' and status='answered')
with check (auth.uid()=user_id and service_type='remote_programming' and status='payment_submitted' and whatsapp_phone is not null and whatsapp_consent=true and receipt_path is not null);
create index if not exists service_inquiries_user_created_idx on public.service_inquiries(user_id,created_at desc);
create index if not exists service_inquiries_status_created_idx on public.service_inquiries(status,created_at desc);

drop policy if exists "Customers submit remote service payment" on public.service_inquiries;
create or replace function public.astro_submit_remote_service_payment(p_inquiry_id bigint,p_whatsapp_phone text,p_receipt_path text)
returns void language plpgsql security definer set search_path=public as $$
begin
 if auth.uid() is null then raise exception 'Authentication required'; end if;
 if length(trim(coalesce(p_whatsapp_phone,'')))<7 then raise exception 'Valid WhatsApp number required'; end if;
 if length(trim(coalesce(p_receipt_path,'')))=0 or p_receipt_path not like 'service-payments/%' then raise exception 'Valid receipt path required'; end if;
 update public.service_inquiries set whatsapp_phone=trim(p_whatsapp_phone),whatsapp_consent=true,receipt_path=p_receipt_path,status='payment_submitted',payment_submitted_at=now(),updated_at=now()
 where id=p_inquiry_id and user_id=auth.uid() and service_type='remote_programming' and status='answered' and quoted_price is not null;
 if not found then raise exception 'This service inquiry is not eligible for payment'; end if;
end; $$;
revoke all on function public.astro_submit_remote_service_payment(bigint,text,text) from public;
grant execute on function public.astro_submit_remote_service_payment(bigint,text,text) to authenticated;


-- Notify admin devices and the submitting customer's registered app when a remote
-- programming receipt is submitted. The FCM function validates the secret and
-- records delivery results in astro_notification_history.
create or replace function public.notify_service_payment_submitted()
returns trigger
language plpgsql
security definer
set search_path = public, vault, net
as $$
declare
  v_project_url text;
  v_admin_secret text;
  v_history_id bigint;
  v_admin_body text;
  v_customer_body text;
begin
  if new.status = 'payment_submitted'
     and old.status is distinct from new.status
     and new.service_type = 'remote_programming' then
    select decrypted_secret into v_project_url
      from vault.decrypted_secrets where name = 'astro_project_url' limit 1;
    select decrypted_secret into v_admin_secret
      from vault.decrypted_secrets where name = 'astro_admin_notification_secret' limit 1;
    if v_project_url is null or v_admin_secret is null then
      raise warning 'Service payment notification skipped: notification secrets are missing';
      return new;
    end if;

    v_admin_body := 'تم استلام إيصال برمجة الهاتف ' || coalesce(new.device_model, '') ||
      '، رقم الاستفسار #' || new.id || '. يرجى مراجعة الإيصال من لوحة الإدارة.';
    insert into public.astro_notification_history(title,body,sent_by,delivery_status)
      values ('إيصال خدمة برمجة جديد',v_admin_body,'system:service_inquiries','queued')
      returning id into v_history_id;
    perform net.http_post(
      url := v_project_url || '/functions/v1/fcm-send',
      headers := jsonb_build_object('Content-Type','application/json','x-admin-secret',v_admin_secret),
      body := jsonb_build_object('title','إيصال خدمة برمجة جديد','body',v_admin_body,
        'audience','admin','history_id',v_history_id)
    );

    v_customer_body := 'تم استلام إيصالك لطلب برمجة الهاتف ' ||
      coalesce(new.device_model,'') || '، وسيتم مراجعته وتأكيد الدفع.';
    insert into public.astro_notification_history(title,body,sent_by,delivery_status)
      values ('تم استلام إيصالك',v_customer_body,'system:service_inquiries','queued')
      returning id into v_history_id;
    perform net.http_post(
      url := v_project_url || '/functions/v1/fcm-send',
      headers := jsonb_build_object('Content-Type','application/json','x-admin-secret',v_admin_secret),
      body := jsonb_build_object('title','تم استلام إيصالك','body',v_customer_body,
        'audience','customers','phone',new.whatsapp_phone,'history_id',v_history_id)
    );
  end if;
  return new;
end;
$$;

drop trigger if exists trg_notify_service_payment_submitted on public.service_inquiries;
create trigger trg_notify_service_payment_submitted
after update of status on public.service_inquiries
for each row execute function public.notify_service_payment_submitted();
revoke all on function public.notify_service_payment_submitted() from public, anon, authenticated;


-- Notify admin when a service inquiry is created.
create or replace function public.notify_new_service_inquiry()
returns trigger
language plpgsql
security definer
set search_path = public, vault, net
as $$
declare v_url text; v_secret text; v_history bigint; v_body text;
begin
  select decrypted_secret into v_url from vault.decrypted_secrets where name='astro_project_url' limit 1;
  select decrypted_secret into v_secret from vault.decrypted_secrets where name='astro_admin_notification_secret' limit 1;
  if v_url is null or v_secret is null then
    raise warning 'New service inquiry notification skipped: secrets missing';
    return new;
  end if;
  v_body := 'استفسار خدمة جديد: ' || coalesce(new.device_model,'') || ' - ' ||
    case new.service_type when 'maintenance' then 'الصيانة' when 'software' then 'السوفتوير' else 'برمجة الهاتف' end ||
    '، رقم الاستفسار #' || new.id || '.';
  insert into public.astro_notification_history(title,body,sent_by,delivery_status)
    values ('استفسار خدمة جديد',v_body,'system:service_inquiries','queued') returning id into v_history;
  perform net.http_post(url := v_url || '/functions/v1/fcm-send',
    headers := jsonb_build_object('Content-Type','application/json','x-admin-secret',v_secret),
    body := jsonb_build_object('title','استفسار خدمة جديد','body',v_body,'audience','admin','history_id',v_history));
  return new;
end;
$$;

-- Notify the owner when the admin changes an inquiry to answered.
create or replace function public.notify_service_inquiry_answered()
returns trigger
language plpgsql
security definer
set search_path = public, vault, net, auth
as $$
declare v_url text; v_secret text; v_phone text; v_history bigint; v_body text;
begin
  if new.status = 'answered' and old.status is distinct from new.status then
    select decrypted_secret into v_url from vault.decrypted_secrets where name='astro_project_url' limit 1;
    select decrypted_secret into v_secret from vault.decrypted_secrets where name='astro_admin_notification_secret' limit 1;
    select case
      when regexp_replace(coalesce(email,''),'@.*$','','i') like '218%' then '+' || regexp_replace(email,'@.*$','','i')
      when regexp_replace(coalesce(email,''),'@.*$','','i') like '0%' then '+218' || substring(regexp_replace(email,'@.*$','','i') from 2)
      else null end into v_phone from auth.users where id=new.user_id;
    if v_url is null or v_secret is null or v_phone is null then
      raise warning 'Service answer notification skipped: missing config or account phone';
      return new;
    end if;
    v_body := 'تم الرد على استفسارك بخصوص ' || coalesce(new.device_model,'') ||
      '. افتح تطبيق ASTRO MOBILE للاطلاع على رد الإدارة.';
    insert into public.astro_notification_history(title,body,sent_by,delivery_status)
      values ('تم الرد على استفسارك',v_body,'system:service_inquiries','queued') returning id into v_history;
    perform net.http_post(url := v_url || '/functions/v1/fcm-send',
      headers := jsonb_build_object('Content-Type','application/json','x-admin-secret',v_secret),
      body := jsonb_build_object('title','تم الرد على استفسارك','body',v_body,'audience','customers','phone',v_phone,'history_id',v_history));
  end if;
  return new;
end;
$$;

drop trigger if exists trg_notify_new_service_inquiry on public.service_inquiries;
create trigger trg_notify_new_service_inquiry after insert on public.service_inquiries
for each row execute function public.notify_new_service_inquiry();
revoke all on function public.notify_new_service_inquiry() from public, anon, authenticated;

drop trigger if exists trg_notify_service_inquiry_answered on public.service_inquiries;

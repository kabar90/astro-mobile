-- ASTRO MOBILE service inquiry workflow
create table if not exists public.service_inquiries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  service_type text not null check (service_type in ('maintenance','software','remote_programming')),
  device_model text not null check (char_length(trim(device_model)) between 2 and 120),
  request_details text not null check (char_length(trim(request_details)) between 3 and 2000),
  status text not null default 'new' check (status in ('new','in_progress','answered','unavailable','awaiting_payment','payment_submitted','paid','closed')),
  admin_reply text,
  quoted_price numeric(10,2) check (quoted_price is null or quoted_price >= 0),
  whatsapp_phone text,
  whatsapp_consent boolean not null default false,
  receipt_path text,
  payment_submitted_at timestamptz,
  payment_confirmed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint remote_contact_consent check (service_type <> 'remote_programming' or ((whatsapp_phone is null and whatsapp_consent=false) or (whatsapp_phone is not null and whatsapp_consent=true))),
  constraint in_person_no_remote_payment check (service_type='remote_programming' or (receipt_path is null and whatsapp_phone is null and whatsapp_consent=false))
);
alter table public.service_inquiries enable row level security;
-- Data API privileges; row access remains restricted by the RLS policies below.
grant select, insert, update on table public.service_inquiries to authenticated;
drop policy if exists "Customers create own service inquiries" on public.service_inquiries;
create policy "Customers create own service inquiries" on public.service_inquiries for insert to authenticated with check (auth.uid()=user_id);
drop policy if exists "Customers read own service inquiries" on public.service_inquiries;
create policy "Customers read own service inquiries" on public.service_inquiries for select to authenticated using (auth.uid()=user_id or (auth.jwt()->>'email')='ahmedkabar.ak@gmail.com');
drop policy if exists "Admin manages service inquiries" on public.service_inquiries;
create policy "Admin manages service inquiries" on public.service_inquiries for all to authenticated using ((auth.jwt()->>'email')='ahmedkabar.ak@gmail.com') with check ((auth.jwt()->>'email')='ahmedkabar.ak@gmail.com');
drop policy if exists "Customers submit remote service payment" on public.service_inquiries;
create policy "Customers submit remote service payment" on public.service_inquiries for update to authenticated
using (auth.uid()=user_id and service_type='remote_programming' and status='answered')
with check (auth.uid()=user_id and service_type='remote_programming' and status='payment_submitted' and whatsapp_phone is not null and whatsapp_consent=true and receipt_path is not null);
create index if not exists service_inquiries_user_created_idx on public.service_inquiries(user_id,created_at desc);
create index if not exists service_inquiries_status_created_idx on public.service_inquiries(status,created_at desc);

drop policy if exists "Customers submit remote service payment" on public.service_inquiries;
create or replace function public.astro_submit_remote_service_payment(p_inquiry_id bigint,p_whatsapp_phone text,p_receipt_path text)
returns void language plpgsql security definer set search_path=public as $$
begin
 if auth.uid() is null then raise exception 'Authentication required'; end if;
 if length(trim(coalesce(p_whatsapp_phone,'')))<7 then raise exception 'Valid WhatsApp number required'; end if;
 if length(trim(coalesce(p_receipt_path,'')))=0 or p_receipt_path not like 'service-payments/%' then raise exception 'Valid receipt path required'; end if;
 update public.service_inquiries set whatsapp_phone=trim(p_whatsapp_phone),whatsapp_consent=true,receipt_path=p_receipt_path,status='payment_submitted',payment_submitted_at=now(),updated_at=now()
 where id=p_inquiry_id and user_id=auth.uid() and service_type='remote_programming' and status='answered' and quoted_price is not null;
 if not found then raise exception 'This service inquiry is not eligible for payment'; end if;
end; $$;
revoke all on function public.astro_submit_remote_service_payment(bigint,text,text) from public;
grant execute on function public.astro_submit_remote_service_payment(bigint,text,text) to authenticated;

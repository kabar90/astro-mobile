-- ASTRO MOBILE: authenticated product inquiries for screen protectors and cases.
-- Run once in Supabase SQL Editor. Does not alter orders, payments, points, or storage.

create table if not exists public.product_inquiries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category_id bigint not null check (category_id in (17, 34, 40)),
  device_model text not null check (char_length(trim(device_model)) between 2 and 100),
  customer_note text,
  status text not null default 'new'
    check (status in ('new', 'in_progress', 'answered', 'closed')),
  admin_reply text,
  recommended_product_ids jsonb not null default '[]'::jsonb
    check (jsonb_typeof(recommended_product_ids) = 'array'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  answered_at timestamptz
);

alter table public.product_inquiries
  add column if not exists admin_image_urls jsonb not null default '[]'::jsonb
  check (jsonb_typeof(admin_image_urls) = 'array');

create index if not exists product_inquiries_user_created_idx
  on public.product_inquiries (user_id, created_at desc);
create index if not exists product_inquiries_status_created_idx
  on public.product_inquiries (status, created_at desc);

alter table public.product_inquiries enable row level security;

drop policy if exists "customers create own authenticated inquiries" on public.product_inquiries;
create policy "customers create own authenticated inquiries"
  on public.product_inquiries for insert to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "customers read own inquiries" on public.product_inquiries;
create policy "customers read own inquiries"
  on public.product_inquiries for select to authenticated
  using (
    auth.uid() = user_id
    or lower(coalesce(auth.jwt() ->> 'email', '')) = 'ahmedkabar.ak@gmail.com'
  );

drop policy if exists "admin updates inquiries" on public.product_inquiries;
create policy "admin updates inquiries"
  on public.product_inquiries for update to authenticated
  using (lower(coalesce(auth.jwt() ->> 'email', '')) = 'ahmedkabar.ak@gmail.com')
  with check (lower(coalesce(auth.jwt() ->> 'email', '')) = 'ahmedkabar.ak@gmail.com');

grant select, insert on public.product_inquiries to authenticated;
grant update on public.product_inquiries to authenticated;

create or replace function public.set_product_inquiry_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  if new.status = 'answered' and old.status is distinct from 'answered' then
    new.answered_at = now();
  end if;
  return new;
end;
$$;

drop trigger if exists product_inquiries_updated_at on public.product_inquiries;
create trigger product_inquiries_updated_at
before update on public.product_inquiries
for each row execute function public.set_product_inquiry_updated_at();
